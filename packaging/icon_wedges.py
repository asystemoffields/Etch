#!/usr/bin/env python3
"""Draw Etch's app icon, assets/app-icon/wordcraft.svg: an E of cuneiform-style stylus wedges
pressed into a terracotta tablet. Run from the repository root, then packaging/icons.sh renders
every size. Original artwork; MIT OR Apache-2.0."""
import math
LIGHT=(-1/math.sqrt(2),-1/math.sqrt(2))
def hexrgb(h): return [int(h[i:i+2],16) for i in (1,3,5)]
def mix(a,b,t):
    a,b=hexrgb(a),hexrgb(b); return '#'+''.join(f'{round(x+(y-x)*t):02X}' for x,y in zip(a,b))
N=[0]
def wedge(x,y,ang,h,length,surface,deep):
    """A stylus impression: deepest at the head, the tail shallowing out into the surface."""
    N[0]+=1; gid=f'w{N[0]}'
    c,s=math.cos(math.radians(ang)),math.sin(math.radians(ang))
    P=lambda u,v:(x+u*c-v*s,y+u*s+v*c)
    A,B,T,D=P(0,-h),P(0,h),P(length,0),P(h*0.62,0)
    tx,ty=T
    out=[f'<linearGradient id="{gid}" gradientUnits="userSpaceOnUse" x1="{D[0]:.1f}" y1="{D[1]:.1f}" x2="{tx:.1f}" y2="{ty:.1f}"><stop offset="0" stop-color="#fff"/><stop offset="0.45" stop-color="#fff" stop-opacity="0.92"/><stop offset="1" stop-color="#fff" stop-opacity="0.1"/></linearGradient>',
         f'<mask id="m{gid}"><rect width="512" height="512" fill="url(#{gid})"/></mask>',
         f'<g mask="url(#m{gid})">']
    for e1,e2 in ((A,B),(A,T),(B,T)):
        mx,my=(e1[0]+e2[0])/2,(e1[1]+e2[1])/2
        nx,ny=D[0]-mx,D[1]-my; d=math.hypot(nx,ny) or 1
        b=0.5+0.5*((nx/d)*LIGHT[0]+(ny/d)*LIGHT[1])   # 1: faces the light
        col=mix(deep,surface,0.04+0.84*b**1.5)          # never brighter than the surface
        out.append(f'<path d="M{e1[0]:.1f} {e1[1]:.1f} L{e2[0]:.1f} {e2[1]:.1f} L{D[0]:.1f} {D[1]:.1f} Z" fill="{col}" stroke="{col}" stroke-width="0.8" stroke-linejoin="round"/>')
    out.append('</g>')
    # Only the far lip (opposite the light) catches a little light, near the head.
    hx,hy=P(-1.5,0)
    return '\n    '.join(out)
def tile(body, top, bot):
    return f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512">
  <!-- Etch app icon: an E of stylus wedges pressed into a clay tablet (original; MIT OR Apache-2.0). Generated by packaging/icon_wedges.py; the wedges are three shaded facets each, lit from the upper left. -->
  <defs>
    <linearGradient id="clay" x1="0" y1="0" x2="0.4" y2="1">
      <stop offset="0" stop-color="{top}"/>
      <stop offset="1" stop-color="{bot}"/>
    </linearGradient>
    <linearGradient id="rim" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="#FBD9BE" stop-opacity="0.85"/>
      <stop offset="0.5" stop-color="#FBD9BE" stop-opacity="0"/>
      <stop offset="0.5" stop-color="#3A1608" stop-opacity="0"/>
      <stop offset="1" stop-color="#3A1608" stop-opacity="0.6"/>
    </linearGradient>
    <filter id="grain" x="0" y="0" width="1" height="1">
      <feTurbulence type="fractalNoise" baseFrequency="1.6" numOctaves="1" seed="7" result="n"/>
      <feColorMatrix in="n" type="matrix" values="0 0 0 0 0.22  0 0 0 0 0.09  0 0 0 0 0.03  0 0 0 0.07 0"/>
      <feComposite in2="SourceGraphic" operator="in"/>
    </filter>
  </defs>
  <rect width="512" height="512" rx="112" fill="url(#clay)"/>
  <rect width="512" height="512" rx="112" fill="#000" filter="url(#grain)"/>
  <rect x="5" y="5" width="502" height="502" rx="107" fill="none" stroke="url(#rim)" stroke-width="10"/>
  {body}
</svg>
'''
def E(surface,deep):
    N[0]=0
    return '\n  '.join([wedge(176,100,90,56,304,surface,deep), wedge(222,144,0,52,200,surface,deep),
                        wedge(222,272,0,48,164,surface,deep), wedge(222,398,0,52,200,surface,deep)])
variants={'assets/app-icon/wordcraft':('#CD9168','#9A5434','#B97A55','#2A1006')}
for name,(top,bot,surface,deep) in variants.items():
    open(name+'.svg','w').write(tile(E(surface,deep),top,bot))
